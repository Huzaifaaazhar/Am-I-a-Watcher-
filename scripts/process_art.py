#!/usr/bin/env python3
"""
Process the supplied fan artwork into the web-ready set, and write
public/ASSETS.md from the same manifest.

    python3 scripts/process_art.py

Needs Pillow. Nothing in public/art/ is committed by hand: if a file is there
it got there through this script, so the licence record in ASSETS.md cannot
drift from what actually shipped.

The source painting is 736x414. It is displayed as the full canvas
centrepiece, which on a 1440 desktop means roughly a 2x upscale, so the 2k
derivative is resampled with Lanczos and then given a light unsharp pass:
without it the upscale reads as a blurred photograph rather than as a
painting. A watercolour tolerates this far better than a photo would - there
is no fine texture to invent, only washes.

WebP, lossy, quality 88. The painting is all soft gradients, which is exactly
what lossy WebP is good at; the same image as lossless PNG is 11x the bytes
for no visible difference at these sizes.

The animated GIF that came with the artwork is deliberately not shipped. It is
540x450 and 10 MB - a third of the pixels needed for the canvas and more
weight than the entire rest of the app, and stretching it would break the
aspect-ratio contract the SVG overlay depends on.
"""

from __future__ import annotations

import sys
from pathlib import Path

try:
    from PIL import Image, ImageFilter
except ImportError:
    sys.exit("needs Pillow:  pip install Pillow")

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art-src"
OUT = ROOT / "public" / "art"

# 2x the source, which covers a 1440-wide desktop canvas without upscaling in
# the browser as well; 1x for phones, where the canvas is never wider than the
# source anyway.
VARIANTS = {"2k": 2.0, "1k": 1.0}
QUALITY = 88


def process(name: str, src_name: str) -> list[tuple[str, int, tuple[int, int]]]:
    src = SRC / src_name
    if not src.exists():
        sys.exit(f"missing source: {src}")

    image = Image.open(src).convert("RGB")
    written: list[tuple[str, int, tuple[int, int]]] = []
    OUT.mkdir(parents=True, exist_ok=True)

    for tier, factor in VARIANTS.items():
        size = (round(image.width * factor), round(image.height * factor))
        out = image if factor == 1.0 else image.resize(size, Image.LANCZOS)
        if factor > 1.0:
            # Radius tracks the upscale factor: sharpening at a 1px radius
            # after a 2x resample only crisps the resampling artefacts.
            out = out.filter(
                ImageFilter.UnsharpMask(radius=factor, percent=72, threshold=3)
            )
        path = OUT / f"{name}_{tier}.webp"
        out.save(path, "WEBP", quality=QUALITY, method=6)
        written.append((path.name, path.stat().st_size, size))
        print(f"  {path.relative_to(ROOT)}  {size[0]}x{size[1]}  "
              f"{path.stat().st_size / 1024:.0f} KB")

    return written


def write_assets_md(files: list[tuple[str, int, tuple[int, int]]]) -> None:
    total = sum(size for _, size, _ in files)
    lines = [
        "# Assets",
        "",
        "Generated by `python3 scripts/process_art.py`. Do not edit by hand.",
        "",
        "## Cosmic world tree (fan artwork)",
        "",
        "Supplied by the project owner as `art-src/world-tree.jpg` and used as",
        "the centrepiece of the Sacred Timeline canvas. Rendered here only as a",
        "background plate; the interactive structure over it is original SVG.",
        "",
        "No official or copyrighted film asset, logo or title font is reproduced",
        "anywhere in this project.",
        "",
        "| File | Dimensions | Size |",
        "| --- | --- | --- |",
    ]
    for name, size, dims in sorted(files):
        lines.append(f"| `public/art/{name}` | {dims[0]}x{dims[1]} | {size / 1024:.0f} KB |")
    lines += [
        "",
        f"Total shipped: {total / 1024:.0f} KB.",
        "",
        "## Fonts",
        "",
        "Bitter and JetBrains Mono, both SIL Open Font License 1.1, self-hosted",
        "through `next/font` - no CDN, and no copyrighted title face.",
        "",
    ]
    (ROOT / "public" / "ASSETS.md").write_text("\n".join(lines))
    print(f"  wrote public/ASSETS.md  ({total / 1024:.0f} KB of assets)")


def main() -> None:
    print("processing artwork...")
    files = process("world-tree", "world-tree.jpg")
    write_assets_md(files)


if __name__ == "__main__":
    main()
